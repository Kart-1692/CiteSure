"""Turn results/metrics.json into the files the paper includes.

    python -m eval.make_report                    # results/metrics.json -> paper/generated/
    python -m eval.make_report --placeholder      # empty tables (what the repo ships with)

Writes paper/generated/results.tex (number macros + table bodies), two figures and
results/summary.md (the same numbers in plain sentences, to check the prose against).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

PH = "--"


def f(v, suffix=""):
    return PH if v is None else f"{v}{suffix}"


def tex_escape(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&"), ("#", r"\#"), ("$", r"\$")):
        s = s.replace(a, b)
    return s


def build(metrics: dict | None, fig_ok: bool) -> str:
    m = metrics or {}
    meta, main, refs = m.get("meta", {}), m.get("main", {}), m.get("references", {})
    retr, ver, ab, modes = m.get("retrieval", {}), m.get("verification", {}), m.get("abstention", {}), m.get("by_mode", {})
    g = lambda d, *ks: (lambda x: x)(_dig(d, ks))

    macros = {
        "ResLLM": tex_escape(str(meta.get("llm", PH))), "ResEmbedder": tex_escape(str(meta.get("embedder", PH)).split("/")[-1]),
        "ResJudge": tex_escape(str(meta.get("judge", PH)).split("/")[-1]), "ResDate": meta.get("date", PH),
        "ResNPapers": f(meta.get("n_papers")), "ResNChunks": f(meta.get("n_chunks")),
        "ResNAsk": f(meta.get("n_ask")), "ResNCross": f(meta.get("n_cross")),
        "ResNUnans": f(meta.get("n_unanswerable")), "ResNPaperTasks": f(meta.get("n_paper_tasks")),
        "ResCRbase": f(g(main, "baseline", "citation_recall")), "ResCPbase": f(g(main, "baseline", "citation_precision")),
        "ResFAbase": f(g(main, "baseline", "faithfulness")),
        "ResCRdraft": f(g(main, "draft", "citation_recall")), "ResCPdraft": f(g(main, "draft", "citation_precision")),
        "ResFAdraft": f(g(main, "draft", "faithfulness")),
        "ResCRver": f(g(main, "verified", "citation_recall")), "ResCPver": f(g(main, "verified", "citation_precision")),
        "ResFAver": f(g(main, "verified", "faithfulness")),
        "ResRefTotal": f(refs.get("total")), "ResRefChecked": f(refs.get("checked")),
        "ResRefFab": f(refs.get("fabricated")), "ResRefFabPct": f(refs.get("fabricated_pct")),
        "ResRefInCorpus": f(refs.get("real_in_corpus")), "ResRefOutside": f(refs.get("real_outside")),
        "ResRefUnchecked": f(refs.get("unchecked")), "ResRefErr": f(refs.get("metadata_errors")),
        "ResRefErrPct": f(refs.get("metadata_error_pct")),
        "ResDraftN": f(ver.get("draft_statements")), "ResRemovedN": f(ver.get("removed")),
        "ResRemovedPct": f(ver.get("removed_pct")),
        "ResAbstainSys": f(ab.get("system_abstained_pct")), "ResAbstainBase": f(ab.get("baseline_abstained_pct")),
        "ResFalseAbstain": f(ab.get("system_false_abstention_pct")),
        "ResSecBase": f(g(main, "baseline", "seconds_per_answer")), "ResSecDraft": f(g(main, "draft", "seconds_per_answer")),
        "ResSecVer": f(g(main, "verified", "seconds_per_answer")),
        "ResCallsVer": f(g(main, "verified", "llm_calls_per_answer")),
        "ResUncitedBase": f(g(main, "baseline", "uncited_pct")),
    }
    out = ["% Generated by eval/make_report.py - do not edit by hand."]
    out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    smoke = bool(meta.get("smoke"))
    out.append("\\newcommand{\\ResNote}{%s}" % (
        "\\textbf{SMOKE-TEST NUMBERS: mock model or lexical judge. Not for reporting.} " if smoke else ""))

    def r3(name, key):
        d = main.get(key, {})
        return (f"{name} & {f(d.get('citation_recall'))} & {f(d.get('citation_precision'))} & {f(d.get('faithfulness'))} & "
                f"{f(d.get('statements_per_answer'))} & {f(d.get('llm_calls_per_answer'))} & {f(d.get('seconds_per_answer'))} \\\\")

    out.append("\\newcommand{\\ResTableMain}{%\n\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n"
               "System & Cit.\\ rec. & Cit.\\ prec. & Faithf. & Stmts & Calls & Time (s) \\\\\n\\midrule\n"
               + r3("Plain LLM (no documents)", "baseline") + "\n" + r3("Grounded, no verification", "draft") + "\n"
               + r3("Grounded + verification", "verified") + "\n\\bottomrule\n\\end{tabular}}")

    out.append("\\newcommand{\\ResTableRefs}{%\n\\begin{tabular}{@{}lcc@{}}\n\\toprule\nReference status & Count & Share (\\%) \\\\\n\\midrule\n"
               f"Not found in any registry (fabricated) & {macros['ResRefFab']} & {macros['ResRefFabPct']} \\\\\n"
               f"Real, in the corpus & {macros['ResRefInCorpus']} & {f(_pct(refs.get('real_in_corpus'), refs.get('checked')))} \\\\\n"
               f"Real, outside the corpus & {macros['ResRefOutside']} & {f(_pct(refs.get('real_outside'), refs.get('checked')))} \\\\\n"
               "\\midrule\n"
               f"Real but wrong year or first author & {macros['ResRefErr']} & {macros['ResRefErrPct']} \\\\\n"
               f"Could not be checked (no registry reachable) & {macros['ResRefUnchecked']} & n/a \\\\\n"
               "\\bottomrule\n\\end{tabular}}")

    def rr(name, key):
        d = retr.get(key, {})
        return f"{name} & {f(d.get('hit'))} & {f(d.get('coverage'))} & {f(d.get('mrr'))} \\\\"

    out.append("\\newcommand{\\ResTableRetrieval}{%\n\\begin{tabular}{@{}lccc@{}}\n\\toprule\n"
               "Retriever & Hit@$k$ (\\%) & Gold coverage (\\%) & MRR \\\\\n\\midrule\n"
               + rr("Dense only", "dense") + "\n" + rr("BM25 only", "bm25") + "\n" + rr("Hybrid (RRF)", "hybrid")
               + "\n\\bottomrule\n\\end{tabular}}")

    rows = []
    for label, key in (("Ask Research", "ask"), ("Explain Paper", "explain"), ("Summarize Paper", "summarize")):
        v, b = _dig(modes, (key, "verified")) or {}, _dig(modes, (key, "baseline")) or {}
        rows.append(f"{label} & {f(v.get('citation_recall'))} & {f(v.get('citation_precision'))} & {f(v.get('faithfulness'))} & "
                    f"{f(b.get('faithfulness'))} & {f(v.get('interpretations'))} \\\\")
    out.append("\\newcommand{\\ResTableModes}{%\n\\begin{tabular}{@{}lccccc@{}}\n\\toprule\n"
               "Mode & Cit.\\ rec. & Cit.\\ prec. & Faithf. & Plain LLM faithf. & Interp. \\\\\n\\midrule\n"
               + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}}")

    if fig_ok:
        out.append("\\newcommand{\\ResFigMain}{\\includegraphics[width=\\columnwidth]{generated/fig_main.pdf}}")
    else:
        out.append("\\newcommand{\\ResFigMain}{\\fbox{\\parbox[c][3.2cm][c]{0.92\\columnwidth}{\\centering\\footnotesize "
                   "Bar chart of Table~IV.\\\\Written to \\texttt{generated/fig\\_main.pdf} by \\texttt{eval/make\\_report.py}"
                   " after the evaluation run.}}}")
    return "\n".join(out) + "\n"


def _dig(d, keys):
    for k in keys:
        d = d.get(k) if isinstance(d, dict) else None
    return d


def _pct(a, b):
    return round(100.0 * a / b, 1) if a is not None and b else None


def figure(metrics: dict, path: Path) -> bool:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    names = [("baseline", "Plain LLM"), ("draft", "Grounded,\nno verification"), ("verified", "Grounded +\nverification")]
    keys = [("citation_recall", "Citation recall"), ("citation_precision", "Citation precision"), ("faithfulness", "Faithfulness")]
    if any(metrics["main"][n][k] is None for n, _ in names for k, _ in keys if n != "baseline"):
        return False
    fig, ax = plt.subplots(figsize=(3.5, 2.3))
    width, hatches, shades = 0.26, ["", "///", "..."], ["0.25", "0.6", "0.85"]
    for i, (k, label) in enumerate(keys):
        raw = [metrics["main"][n][k] for n, _ in names]
        bars = ax.bar([x + (i - 1) * width for x in range(3)], [v or 0 for v in raw], width, label=label,
                      color=shades[i], edgecolor="black", linewidth=0.5, hatch=hatches[i])
        for bar, v in zip(bars, raw):
            ax.text(bar.get_x() + bar.get_width() / 2, (v or 0) + 1.5, "n/a" if v is None else f"{v:.0f}",
                    ha="center", va="bottom", fontsize=6)
    ax.set_xticks(range(3), [n for _, n in names], fontsize=7)
    ax.set_ylabel("Percent", fontsize=7)
    ax.set_ylim(0, 112)
    ax.tick_params(axis="y", labelsize=7)
    ax.legend(fontsize=6, ncol=3, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.16), columnspacing=1.0, handlelength=1.4)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    fig.tight_layout(pad=0.3)
    fig.savefig(path)
    plt.close(fig)
    return True


def summary(m: dict) -> str:
    a, d, v, b = m["meta"], m["main"]["draft"], m["main"]["verified"], m["main"]["baseline"]
    r, ver, ab = m["references"], m["verification"], m["abstention"]
    lines = [
        f"# Evaluation summary ({a['date']})", "",
        ("**SMOKE RUN - numbers are not reportable.**\n" if a["smoke"] else ""),
        f"- Setup: {a['n_papers']} papers, {a['n_chunks']} chunks; {a['n_ask']} questions ({a['n_cross']} cross-paper), "
        f"{a['n_unanswerable']} out-of-corpus questions, {a['n_paper_tasks']} papers for Explain and Summarize.",
        f"- Models: generator/verifier `{a['llm']}`, embedder `{a['embedder']}`, judge `{a['judge']}`.",
        f"- Citation recall: plain LLM {b['citation_recall']}, grounded without verification {d['citation_recall']}, full system {v['citation_recall']}.",
        f"- Citation precision: plain LLM {b['citation_precision']}, without verification {d['citation_precision']}, full system {v['citation_precision']}.",
        f"- Faithfulness: plain LLM {b['faithfulness']}, without verification {d['faithfulness']}, full system {v['faithfulness']}.",
        f"- Verification removed {ver['removed']} of {ver['draft_statements']} drafted statements ({ver['removed_pct']}%). Reasons: {ver['reasons']}.",
        f"- Plain-LLM references: {r['total']} written, {r['checked']} checked, {r['fabricated']} not found in any registry "
        f"({r['fabricated_pct']}%), {r['metadata_errors']} real ones with a wrong year or first author ({r['metadata_error_pct']}%).",
        f"- Out-of-corpus questions: system declined {ab['system_abstained_pct']}%, plain LLM declined {ab['baseline_abstained_pct']}%. "
        f"False abstention on answerable requests: {ab['system_false_abstention_pct']}%.",
        f"- Retrieval (Hit@k / coverage / MRR): " + "; ".join(f"{k}: {x['hit']} / {x['coverage']} / {x['mrr']}" for k, x in m["retrieval"].items()) + ".",
        f"- Cost per answer: full system {v['llm_calls_per_answer']} LLM calls, {v['seconds_per_answer']} s; plain LLM {b['seconds_per_answer']} s.",
        "", "Read results/removed_claims.jsonl and pick two or three removed claims for the error analysis in Section IV-G.",
    ]
    if a.get("verifier_failures"):
        lines.append(f"\nWARNING: {a['verifier_failures']} verification calls failed and were treated as 'not supported'.")
    return "\n".join(l for l in lines if l is not None)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--metrics", default="results/metrics.json")
    ap.add_argument("--out", default="paper/generated")
    ap.add_argument("--placeholder", action="store_true")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.placeholder:
        here = Path(__file__).parent                     # planned set-up counts; measured values stay "--"
        corpus = json.loads((here / "corpus.json").read_text())
        q = json.loads((here / "questions.json").read_text())
        planned = {"meta": {"n_papers": len(corpus), "n_ask": len(q["ask"]),
                            "n_cross": sum(len(x["gold"]) > 1 for x in q["ask"]),
                            "n_unanswerable": len(q["unanswerable"]), "n_paper_tasks": len(q["paper_tasks"])}}
        (out / "results.tex").write_text(build(planned, False))
        print(f"wrote placeholder {out / 'results.tex'}")
        return 0
    metrics = json.loads(Path(args.metrics).read_text())
    fig_ok = figure(metrics, out / "fig_main.pdf")
    (out / "results.tex").write_text(build(metrics, fig_ok))
    Path(args.metrics).with_name("summary.md").write_text(summary(metrics))
    print(f"wrote {out / 'results.tex'}" + (f", {out / 'fig_main.pdf'}" if fig_ok else "") + " and summary.md")
    if metrics["meta"]["smoke"]:
        print("SMOKE RUN: tables are stamped as not reportable.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
